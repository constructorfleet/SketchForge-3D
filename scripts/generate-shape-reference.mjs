import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { REQUESTABLE_SHAPE_KINDS, shapeParameterNamesFor } from "../packages/sketchforge-engine/dist/shapeRequests.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(root, "docs/SHAPE_REQUEST_REFERENCE.md");

const rows = REQUESTABLE_SHAPE_KINDS.map((kind) => `| \`${kind}\` | ${shapeParameterNamesFor(kind).map((name) => `\`${name}\``).join(", ") || "—"} |`);
const generated = `<!-- Generated by scripts/generate-shape-reference.mjs. Edit the engine registry instead. -->
# Parameterized shape reference

This reference lists shape kinds accepted by parameter based shape creation and the additional fields each kind accepts. Placement and dimensions common to all kinds are omitted. The engine request registry is the source of truth.

| Kind | Additional request fields |
| --- | --- |
${rows.join("\n")}

The \`cube\` kind is an accepted request alias that creates a box with equal side dimensions. Imported meshes and drawn sketches are not parameterized shape requests.
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    // A missing generated file is a stale inventory too.
  }
  if (current !== generated) {
    process.stderr.write("Shape reference is stale. Run node scripts/generate-shape-reference.mjs to update it.\n");
    process.exitCode = 1;
  }
} else {
  await import("node:fs/promises").then(({ writeFile }) => writeFile(outputPath, generated));
}
