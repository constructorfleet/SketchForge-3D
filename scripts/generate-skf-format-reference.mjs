#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "packages/sketchforge-engine/src/skfProject.ts");
const outputPath = path.join(root, "docs/SKF_FORMAT_REFERENCE.md");
const source = readFileSync(sourcePath, "utf8");

function typeBody(name) {
  const declaration = new RegExp(`export type ${name}\\s*=\\s*\\{`).exec(source);
  if (!declaration) throw new Error(`Could not find exported format type ${name}`);
  const start = declaration.index + declaration[0].length - 1;
  let depth = 0;
  for (let index = start; index < source.length; index += 1) {
    if (source[index] === "{") depth += 1;
    if (source[index] === "}" && --depth === 0) return source.slice(start + 1, index);
  }
  throw new Error(`Unclosed format type ${name}`);
}

function fields(name) {
  const lines = typeBody(name).split("\n");
  return lines.map((line, index) => {
    const match = line.match(/^  ([\w]+)(\?)?:\s*(.*)$/);
    if (!match) return null;
    const [, field, optional, initialType] = match;
    let type = initialType;
    for (let next = index + 1; next < lines.length && !/^  [\w]+\??:/.test(lines[next]); next += 1) {
      type += ` ${lines[next].trim()}`;
    }
    type = type.replace(/\s+/g, " ").replace(/;\s*$/, "");
    return `| \`${field}${optional ? "?" : ""}\` | \`${type}\` |`;
  }).filter(Boolean).join("\n");
}

function constant(name) {
  const match = source.match(new RegExp(`export const ${name} = ([^;]+);`));
  if (!match) throw new Error(`Could not find exported format constant ${name}`);
  return match[1];
}

function limits() {
  const body = source.match(/export const SKF_LIMITS = \{([\s\S]*?)\n\} as const;/)?.[1];
  if (!body) throw new Error("Could not find SKF_LIMITS");
  return body.split("\n").map((line) => line.match(/^\s{2}(\w+):\s*(.+),\s*$/))
    .filter(Boolean).map(([, name, value]) => `| \`${name}\` | \`${value.trim()}\` |`).join("\n");
}

if (!source.includes("document.formatVersion === 0") || !source.includes("migrateV0(document)")) {
  throw new Error("V0 compatibility migration changed; update this format reference generator.");
}
if (!source.includes("V1 stored a fresh copy in each node") || !source.includes("document.formatVersion < 1")) {
  throw new Error("V1 compatibility handling changed; update this format reference generator.");
}

const generated = `<!-- Generated by node scripts/generate-skf-format-reference.mjs; edit the engine format types and generator instead. -->
# `.concat("`.skf` format reference\n\n") + `This reference is generated from the engine's exported project types, version constants, and archive limits. It describes the serialized contract; see [the project format guide](./SKF_PROJECT_FORMAT.md) for behavior and safety semantics.

For automated project export from a server-backed project, see [\`POST /exports\` in the REST API guide](./REST_API.md#endpoints).

## Package identity

| Property | Value |
| --- | --- |
| Schema | \`${constant("SKF_SCHEMA_ID").replaceAll('"', "")}\` |
| Current writer format | ${constant("SKF_FORMAT_VERSION")} |
| Minimum reader format | ${constant("SKF_MINIMUM_READER_VERSION")} |
| Created-with version | \`${constant("SKF_CREATED_WITH_VERSION").replaceAll('"', "")}\` |
| Media type | \`${constant("SKF_MEDIA_TYPE").replaceAll('"', "")}\` |

A packaged file is a ZIP with a root \`project.json\` and binary or JSON payloads below \`assets/\`. The archive is validated before restoration. ZIP64 and encrypted entries are not supported.

## Serialized document fields

### \`SkfProjectDocumentV1\`

| Field | Serialized type |
| --- | --- |
${fields("SkfProjectDocumentV1")}

### \`SkfAssetRecordV1\`

| Field | Serialized type |
| --- | --- |
${fields("SkfAssetRecordV1")}

### \`SkfShapeNodeV1\`

| Field | Serialized type |
| --- | --- |
${fields("SkfShapeNodeV1")}

### \`SkfFeatureV1\`

| Field | Serialized type |
| --- | --- |
${fields("SkfFeatureV1")}

## Reader compatibility

- V2 is the current writer format and requires a reader at least version 2.
- V1 packaged projects are accepted and migrate inline display edges into shared assets on import; the next save writes V2.
- V0 legacy JSON projects are accepted by the explicit migration path, which preserves valid object IDs and history.
- Unsupported future versions are rejected before restoration. The original input bytes are not modified.

## Reader safety limits

| Limit | Value |
| --- | ---: |
${limits()}

These are engine validation limits, not suggested project sizes. The expanded archive limit applies across entries; \`assetBytes\` limits one asset, and \`projectJsonBytes\` limits \`project.json\`.
`;

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(outputPath, "utf8"); } catch {}
  if (current !== generated) {
    process.stderr.write("docs/SKF_FORMAT_REFERENCE.md is missing or stale; run node scripts/generate-skf-format-reference.mjs.\n");
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, generated);
}
