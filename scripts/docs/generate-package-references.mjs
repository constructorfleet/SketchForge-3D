import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { spawnSync } from "node:child_process";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const outputDir = path.join(root, "docs/reference");

const ENGINE_API_GROUPS = [
  { title: "Projects and engine operations", test: /^(createEngine|directoryProjectStore|Engine|EngineFailure|EngineResult|Project|ShapeWritten|ShapesWritten|ShapeRemoved|ShapesArranged|AlignOutcome|DistributeOutcome|CutRequest|AlignRequest|DistributeRequest|PatternRequest|MeshImportRequest|Interference|ServerCad|Measurement)/ },
  { title: "Shape construction and placement", test: /(Shape|Request|Kind|Hole|Workplane|Revolve|Loft|Gear|Align|Distribute|Pattern|Bounds|Mirror|Placement|Footprint|Canonical)/ },
  { title: "Project files and geometry exchange", test: /(Import|Export|Step|Skf|Mesh|Scene|Projection|Section|Dxf|Svg)/ },
  { title: "Geometry and CAD", test: /.*/ },
];

function engineApiArea(name) {
  return ENGINE_API_GROUPS.find((group) => group.test.test(name))?.title ?? "Geometry and CAD";
}

async function formatTypeScriptReference(entry, packageName, packagePath, sourcePath) {
  const program = ts.createProgram([entry], { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext, skipLibCheck: true });
  const checker = program.getTypeChecker();
  const moduleSymbol = checker.getSymbolAtLocation(program.getSourceFile(entry));
  if (!moduleSymbol) throw new Error(`Cannot read public declaration module: ${entry}`);
  const exports = checker.getExportsOfModule(moduleSymbol).sort((a, b) => a.getName().localeCompare(b.getName()));
  const lines = [
    `# ${packageName} API`,
    "",
    `Generated from \`${sourcePath}\` by \`node scripts/docs/generate-package-references.mjs\`. Do not edit this file directly.`,
    "",
    packageName === "Engine"
      ? `This reference lists the package's exported declaration surface. Start with the [package guide](../packages/engine.md), or read the [npm package README](https://github.com/constructorfleet/SketchForge-3D/blob/main/${packagePath}/README.md).`
      : `This reference lists the package's exported declaration surface. For usage and behavior, see [the package README](https://github.com/constructorfleet/SketchForge-3D/blob/main/${packagePath}/README.md).`,
    "",
  ];
  if (packageName === "Engine") {
    const readme = await readFile(path.join(root, packagePath, "README.md"), "utf8");
    const guide = readme.replace(/^# .*\n+/, "").trim();
    lines.push(guide, "", "## Exported API", "", "Browse declarations by area, or use the alphabetical links below.", "");
    for (const group of ENGINE_API_GROUPS) {
      const members = exports.filter((symbol) => engineApiArea(symbol.getName()) === group.title);
      if (!members.length) continue;
      lines.push(`### ${group.title}`, "", members.map((symbol) => "[\`" + symbol.getName() + "\`](#" + symbol.getName().toLowerCase() + ")").join(" · "), "");
    }
    lines.push("### All exports", "", exports.map((symbol) => "[\`" + symbol.getName() + "\`](#" + symbol.getName().toLowerCase() + ")").join(" · "), "");
  }
  for (const symbol of exports) {
    const name = symbol.getName();
    const resolvedSymbol = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
    const declaration = resolvedSymbol.getDeclarations()?.find((candidate) => !ts.isExportSpecifier(candidate) && !ts.isImportSpecifier(candidate)) ?? resolvedSymbol.getDeclarations()?.[0];
    const signature = declaration && declaration.getSourceFile().fileName.endsWith(".d.ts")
      ? declaration.getText()
      : checker.typeToString(checker.getTypeOfSymbolAtLocation(symbol, symbol.valueDeclaration ?? program.getSourceFile(entry)), undefined, ts.TypeFormatFlags.NoTruncation);
    const kind = declaration && ts.isInterfaceDeclaration(declaration) ? "interface"
      : declaration && ts.isTypeAliasDeclaration(declaration) ? "type"
        : declaration && ts.isClassDeclaration(declaration) ? "class"
          : declaration && ts.isFunctionDeclaration(declaration) ? "function"
            : "value";
    const docs = ts.displayPartsToString(symbol.getDocumentationComment(checker)).trim();
    lines.push(`${packageName === "Engine" ? "####" : "##"} \`${name}\``, "", `**${kind}**`, "", "```ts", signature, "```");
    if (docs) lines.push("", docs);
    lines.push("");
  }
  return lines.join("\n");
}

const generated = new Map();
for (const [pkg, stem] of [["sketchforge-client", "typescript-client"], ["sketchforge-engine", "typescript-engine"]]) {
  const entry = path.join(root, "packages", pkg, "dist/index.d.ts");
  const markdown = await formatTypeScriptReference(entry, pkg === "sketchforge-client" ? "TypeScript client" : "Engine", `packages/${pkg}`, `packages/${pkg}/dist/index.d.ts`);
  generated.set(`${stem}.md`, markdown);
}

const pythonResult = spawnSync("python3", [path.join(root, "scripts/docs/generate-python-reference.py"), "--stdout"], { cwd: root, encoding: "utf8" });
if (pythonResult.status !== 0) throw new Error(pythonResult.stderr || "Python reference generation failed");
generated.set("python-client.md", pythonResult.stdout);

const docs = await readFile(path.join(root, "docs/DOCUMENTATION_SUITE_SPEC.md"), "utf8");
if (!docs.includes("### Phase 2: generate package and example documentation")) throw new Error("Documentation suite Phase 2 heading is missing");

const check = process.argv.includes("--check");
if (!check) await mkdir(outputDir, { recursive: true });
for (const [filename, markdown] of generated) {
  const outputPath = path.join(outputDir, filename);
  if (check) {
    const current = await readFile(outputPath, "utf8").catch(() => "");
    if (current !== markdown) {
      throw new Error(`${path.relative(root, outputPath)} is missing or stale; run node scripts/docs/generate-package-references.mjs`);
    }
  } else {
    await writeFile(outputPath, markdown);
  }
}
console.log(`${check ? "Checked" : "Generated"} package references in docs/reference/`);
