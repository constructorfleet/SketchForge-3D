#!/usr/bin/env python3
"""Generate a stable Markdown reference from sketchforge3d.__all__."""

from __future__ import annotations

import importlib
import inspect
import dataclasses
import pathlib
import sys
import typing
from typing import Any


ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "packages/sketchforge-py/src"))
package = importlib.import_module("sketchforge3d")


def signature(value: Any) -> str:
    if not getattr(value, "__module__", "").startswith("sketchforge3d"):
        return ""
    try:
        return str(inspect.signature(value)).replace(" = <factory>", " = ...")
    except (TypeError, ValueError):
        return ""


def annotation_text(annotation: Any) -> str:
    if isinstance(annotation, type):
        return annotation.__name__
    return str(annotation).replace("typing.", "")


lines = [
    "# Python client API",
    "",
    "Generated from `packages/sketchforge-py/src/sketchforge3d/__init__.py` by `node scripts/docs/generate-package-references.mjs`. Do not edit this file directly.",
    "",
    "The exported names below are the supported import surface. Signatures and summaries are read from the installed package source; details and examples are in the [Python package README](https://github.com/constructorfleet/SketchForge-3D/blob/main/packages/sketchforge-py/README.md).",
    "",
]

for name in sorted(package.__all__):
    value = getattr(package, name)
    is_typed_dict = typing.is_typeddict(value)
    label = f"`{name}{signature(value)}`" if callable(value) and not is_typed_dict else f"`{name}`"
    lines.extend([f"## {label}", ""])
    if is_typed_dict:
        annotations = typing.get_type_hints(value)
        lines.extend(["```python", f"class {name}:"])
        lines.extend([f"    {field}: {annotation_text(annotation)}" for field, annotation in annotations.items()])
        lines.extend(["```", ""])
    elif isinstance(value, (str, int, float, bool, tuple, list)):
        literal = repr(value)
        if len(literal) <= 240:
            lines.extend([f"`{name} = {literal}`", ""])
    is_package_symbol = getattr(value, "__module__", "").startswith("sketchforge3d")
    doc = inspect.getdoc(value) if is_package_symbol and not is_typed_dict and (inspect.isroutine(value) or inspect.isclass(value)) else None
    if inspect.isclass(value) and dataclasses.is_dataclass(value) and doc and doc.startswith(f"{name}("):
        doc = None
    if doc:
        lines.extend([doc.splitlines()[0], ""])

markdown = "\n".join(lines)
if "--stdout" in sys.argv:
    sys.stdout.write(markdown)
else:
    pathlib.Path(sys.argv[1]).write_text(markdown, encoding="utf-8")
