/** One character per corpus entry: 1 accepted, 0 refused. */
export function verdicts(entries: readonly unknown[], accepts: (value: unknown) => boolean): string {
  return entries.map((entry) => (accepts(entry) ? "1" : "0")).join("");
}

/** One entry per corpus value: `-` when refused, else the value read, or its length when long. */
export function readings(entries: readonly unknown[], read: (value: unknown) => string | undefined): string[] {
  return entries.map((entry) => {
    const value = read(entry);
    if (value === undefined) return "-";
    return value.length > 20 ? `length ${value.length}` : JSON.stringify(value);
  });
}
